import type { Question } from "./scoring.js";

function single(
  id: number,
  text: string,
  options: [string, string, string, string],
  correct: "A" | "B" | "C" | "D",
): Question {
  return {
    id,
    type: "single_choice",
    text,
    options: [
      { id: "A", label: options[0] },
      { id: "B", label: options[1] },
      { id: "C", label: options[2] },
      { id: "D", label: options[3] },
    ],
    correctAnswer: correct,
  };
}

function multi(
  id: number,
  text: string,
  options: string[],
  correct: string[],
): Question {
  const letters = "ABCDEFGH";
  return {
    id,
    type: "multiple_choice",
    text,
    options: options.map((label, i) => ({ id: letters[i], label })),
    correctAnswers: correct,
  };
}

function match(
  id: number,
  text: string,
  rows: string[],
  options: string[],
  pairs: Record<string, string>,
): Question {
  return {
    id,
    type: "matching",
    text,
    rows: rows.map((label, i) => ({ id: String.fromCharCode(65 + i), label })),
    options: options.map((label, i) => ({ id: String(i + 1), label })),
    correctAnswers: pairs,
  };
}

